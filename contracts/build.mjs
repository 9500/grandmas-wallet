// Compiles every contract in this directory and writes, per contract:
//   artifacts/<name>.json  the CashScript artifact (without its timestamp)
//   artifacts/<name>.ts    the compiled bytecode as a hex constant, and the artifact
import { readdirSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { asmToBytecode } from '@cashscript/utils';
import { compileFile } from 'cashc';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, 'artifacts');
mkdirSync(out, { recursive: true });

const toHex = (bytes) => Array.from(bytes, (byte) => byte.toString(16).padStart(2, '0')).join('');

for (const file of readdirSync(here).filter((name) => name.endsWith('.cash'))) {
  const name = file.replace(/\.cash$/, '');
  const { updatedAt: _updatedAt, ...artifact } = compileFile(join(here, file));
  const hex = toHex(asmToBytecode(artifact.bytecode));
  writeFileSync(join(out, `${name}.json`), `${JSON.stringify(artifact, null, 2)}\n`);
  writeFileSync(
    join(out, `${name}.ts`),
    `// Generated by contracts/build.mjs from ${file}. Do not edit.\n` +
      `export const ${name}BytecodeHex =\n  '${hex}';\n\n` +
      `/** The CashScript artifact, as wallets expect it next to a request to sign for this contract. */\n` +
      `export const ${name}Artifact = ${JSON.stringify(artifact, null, 2)};\n`,
  );
  console.log(`${file}: ${hex.length / 2} bytes`);
}
