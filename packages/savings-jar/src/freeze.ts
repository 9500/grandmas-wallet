// Writes the text a wallet is sent: the template of version 4, as it is served and named by hash. Run after a
// deliberate change to the source: `npm run freeze -w @grandmas-wallet/savings-jar`.
import { writeFileSync } from 'node:fs';

import { readTemplate } from '@grandmas-wallet/core';

import { savingsJarV4TemplateSource } from './template-source.js';

const v4Text = JSON.stringify(savingsJarV4TemplateSource);
const v4 = readTemplate(v4Text);
writeFileSync(new URL('../frozen/savings-jar-v4.json', import.meta.url), v4Text);
// The same text as a module, for code that runs without a bundler.
writeFileSync(
  new URL('./frozen.ts', import.meta.url),
  ['// Generated by src/freeze.ts from template-source.ts: the text in frozen/. Do not edit.', `export const savingsJarV4TemplateText: string =\n  ${JSON.stringify(v4Text)};`, ''].join('\n'),
);
console.log(`version 4: template ${v4.identifier}, content ${v4.contentHash}`);
