// Writes the text a wallet is sent for each of Paryon's own deployments, chipnet's and mainnet's, in each version of
// the template: the template, as it is served and named by hash. Run after a deliberate change to the source:
// `npm run freeze -w @grandmas-wallet/paryon`. Version 1 is made as it was frozen and must come out unchanged.
//
// The constants without a version are the latest version, which the pages and runs send; version 1 is reachable only
// under a name that says so.
import { writeFileSync } from 'node:fs';

import { CHIPNET_FAST_PERIODS_6, MAINNET_V1, type ParyonDeployment, paryonContracts } from './deployment.js';
import type { ParyonTemplateVersion } from './template-source.js';
import { paryonTemplateAlone } from './template.js';

const frozen: [constant: string, deployment: ParyonDeployment, version: ParyonTemplateVersion][] = [
  ['paryonChipnetTemplateText', CHIPNET_FAST_PERIODS_6, 2],
  ['paryonMainnetTemplateText', MAINNET_V1, 2],
  ['paryonChipnetTemplateTextV1', CHIPNET_FAST_PERIODS_6, 1],
  ['paryonMainnetTemplateTextV1', MAINNET_V1, 1],
];
const lines = ['// Generated by src/freeze.ts from template-source.ts: the texts in frozen/. Do not edit.'];
for (const [constant, deployment, version] of frozen) {
  const { names, texts } = paryonTemplateAlone(paryonContracts(deployment), version);
  writeFileSync(new URL(`../frozen/paryon-loan-v${version}-${deployment.name}.json`, import.meta.url), texts.template);
  // The same text as a module, for code that runs without a bundler.
  lines.push(`export const ${constant}: string =\n  ${JSON.stringify(texts.template)};`);
  console.log(`${deployment.name}, version ${version}: template ${names.identifier}, content ${names.contentHash}`);
}
writeFileSync(new URL('./frozen.ts', import.meta.url), [...lines, ''].join('\n'));
