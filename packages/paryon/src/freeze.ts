// Writes the text a wallet is sent for each of Paryon's own deployments, chipnet's and mainnet's: the template, as
// it is served and named by hash. Run after a deliberate change to the source: `npm run freeze -w @grandmas-wallet/paryon`.
import { writeFileSync } from 'node:fs';

import { CHIPNET_FAST_PERIODS_6, MAINNET_V1, type ParyonDeployment, paryonContracts } from './deployment.js';
import { paryonTemplateAlone } from './template.js';

const frozen: [constant: string, deployment: ParyonDeployment][] = [
  ['paryonChipnetTemplateText', CHIPNET_FAST_PERIODS_6],
  ['paryonMainnetTemplateText', MAINNET_V1],
];
const lines = ['// Generated by src/freeze.ts from template-source.ts: the texts in frozen/. Do not edit.'];
for (const [constant, deployment] of frozen) {
  const { names, texts } = paryonTemplateAlone(paryonContracts(deployment));
  writeFileSync(new URL(`../frozen/paryon-loan-v1-${deployment.name}.json`, import.meta.url), texts.template);
  // The same text as a module, for code that runs without a bundler.
  lines.push(`export const ${constant}: string =\n  ${JSON.stringify(texts.template)};`);
  console.log(`${deployment.name}: template ${names.identifier}, content ${names.contentHash}`);
}
writeFileSync(new URL('./frozen.ts', import.meta.url), [...lines, ''].join('\n'));
