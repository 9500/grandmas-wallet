// Writes the text a wallet is sent for Paryon's chipnet deployment: the template, as it is served and named by
// hash. Run after a deliberate change to the source: `npm run freeze -w @grandmas-wallet/paryon`.
import { writeFileSync } from 'node:fs';

import { CHIPNET_FAST_PERIODS_6, paryonContracts } from './deployment.js';
import { paryonTemplateAlone } from './template.js';

const { names, texts } = paryonTemplateAlone(paryonContracts(CHIPNET_FAST_PERIODS_6));
writeFileSync(new URL(`../frozen/paryon-loan-v1-${CHIPNET_FAST_PERIODS_6.name}.json`, import.meta.url), texts.template);
// The same text as a module, for code that runs without a bundler.
writeFileSync(
  new URL('./frozen.ts', import.meta.url),
  ['// Generated by src/freeze.ts from template-source.ts: the text in frozen/. Do not edit.', `export const paryonChipnetTemplateText: string =\n  ${JSON.stringify(texts.template)};`, ''].join('\n'),
);
console.log(`template ${names.identifier}, content ${names.contentHash}`);
