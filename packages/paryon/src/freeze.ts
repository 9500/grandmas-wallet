// Writes the texts a wallet is sent for Paryon's chipnet deployment: the template and its recovery declaration,
// as they are served and named by hash. Run after a deliberate change to the source: `npm run freeze -w @grandmas-wallet/paryon`.
import { writeFileSync } from 'node:fs';

import { CHIPNET_FAST_PERIODS_6, paryonContracts } from './deployment.js';
import { paryonTemplateTexts } from './template.js';

const texts = paryonTemplateTexts(paryonContracts(CHIPNET_FAST_PERIODS_6));
const base = `paryon-loan-v1-${CHIPNET_FAST_PERIODS_6.name}`;
writeFileSync(new URL(`../frozen/${base}.json`, import.meta.url), texts.template);
writeFileSync(new URL(`../frozen/${base}.declaration.json`, import.meta.url), texts.declaration);
// The same two texts as a module, for code that runs without a bundler.
writeFileSync(
  new URL('./frozen.ts', import.meta.url),
  [
    '// Generated by src/freeze.ts from template-source.ts: the texts in frozen/. Do not edit.',
    `export const paryonChipnetTemplateText: string =\n  ${JSON.stringify(texts.template)};`,
    '',
    `export const paryonChipnetDeclarationText: string =\n  ${JSON.stringify(texts.declaration)};`,
    '',
  ].join('\n'),
);
console.log(`template ${texts.names.identifier}, content ${texts.names.contentHash}, declaration ${texts.names.declaration}`);
